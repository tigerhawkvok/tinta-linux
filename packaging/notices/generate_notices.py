#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.md: the licenses of everything Tinta's
binaries contain. That is Tinta itself, md4c, the bundled fonts, and merman
with every Rust crate it links (proc-macros run at build time and are left
out). Each crate's own license files come from its source, the cargo
registry or merman's workspace. Identical texts are printed once, with the
crates that use them.

    generate_notices.py --merman SRC --md4c SRC --out FILE [--check]
        [--toolchain 1.95.0] [--features "all-diagrams svg ..."]

--check compares with FILE instead of writing it and fails when stale."""
import argparse
import glob
import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
LICENSE_NAME = re.compile(r'^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE|COPYRIGHT)', re.I)
# One folder down, only font and notice files (ratex-katex-fonts keeps
# KaTeX's OFL and its notice in fonts/)
NESTED_NAME = re.compile(r'^(OFL|FONT_NOTICE|NOTICE|LICEN[CS]E)', re.I)
SKIP_DIRS = {'src', 'tests', 'test', 'examples', 'benches', 'target', '.git'}
MIT_TEXT = """MIT License

Copyright (c) {holder}

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.
"""


def read(path):
    with open(path, encoding='utf-8', errors='replace') as f:
        return f.read().replace('\r\n', '\n').strip() + '\n'


def crates(merman, toolchain, features):
    """(name, version, license, repository, directory) per linked crate"""
    out = subprocess.run(
        ['cargo', '+' + toolchain, 'tree', '--offline', '--manifest-path', os.path.join(merman, 'Cargo.toml'),
         '-p', 'merman-ffi', '--no-default-features', '--features', features, '-e', 'normal',
         '--prefix', 'none', '--format', '{p}|{l}|{r}'],
        capture_output=True, text=True, check=True).stdout
    seen = {}
    for line in out.splitlines():
        if '(proc-macro)' in line or not line.strip():
            continue
        package, license_, repo = (line.replace(' (*)', '').split('|') + ['', ''])[:3]
        m = re.match(r'(\S+) v(\S+)(?: \((.+)\))?', package.strip())
        if not m:
            continue
        name, version, path = m.group(1), m.group(2), m.group(3)
        if (name, version) in seen:
            continue
        if path and os.path.isdir(path):
            directory = path
        else:
            found = glob.glob(os.path.expanduser(f'~/.cargo/registry/src/*/{name}-{version}'))
            directory = found[0] if found else None
        seen[(name, version)] = (name, version, license_.strip(), repo.strip(), directory)
    return sorted(seen.values(), key=lambda c: (c[0].lower(), c[1]))


def license_files(directory):
    if not directory:
        return []
    files = [os.path.join(directory, n) for n in sorted(os.listdir(directory))
             if LICENSE_NAME.match(n) and os.path.isfile(os.path.join(directory, n))]
    for sub in sorted(os.listdir(directory)):
        folder = os.path.join(directory, sub)
        if sub in SKIP_DIRS or not os.path.isdir(folder):
            continue
        files += [os.path.join(folder, n) for n in sorted(os.listdir(folder))
                  if NESTED_NAME.match(n) and os.path.isfile(os.path.join(folder, n))]
    return files


def fenced(text):
    return '```text\n' + text + '```\n'


def build(args):
    parts = ['# Third-party notices\n',
             'Tinta\'s binaries (the Windows exe and the Linux AppImage) contain the software '
             'below. Each license text is reproduced as its project ships it. Generated by '
             '`packaging/notices/generate_notices.py`; do not edit by hand.\n']

    parts.append('## Tinta\n')
    parts.append('This fork of [Tinta](https://github.com/oipoistar/tinta) is distributed under its MIT license:\n')
    parts.append(fenced(read(os.path.join(ROOT, 'LICENSE'))))

    parts.append('## md4c\n')
    parts.append('Markdown parser, [github.com/mity/md4c](https://github.com/mity/md4c):\n')
    parts.append(fenced(read(os.path.join(args.md4c, 'LICENSE.md'))))

    parts.append('## Fonts\n')
    for name, title, url in (('selawik', 'Selawik', 'https://github.com/microsoft/Selawik'),
                             ('monaspace-argon', 'Monaspace Argon', 'https://github.com/githubnext/monaspace')):
        parts.append(f'### {title}\n')
        parts.append(f'[{url}]({url}), SIL Open Font License 1.1:\n')
        parts.append(fenced(read(os.path.join(ROOT, 'third_party', 'fonts', name, 'OFL.txt'))))

    linked = crates(args.merman, args.toolchain, args.features)
    parts.append('## merman and its Rust dependencies\n')
    parts.append('Mermaid rendering, [github.com/Latias94/merman](https://github.com/Latias94/merman), '
                 'with every crate it links. Each crate\'s source is available from its repository or '
                 '[crates.io](https://crates.io) at the version listed, which satisfies the source '
                 'offer of the MPL-2.0 crates.\n')
    parts.append('| Crate | Version | License | Source |\n|---|---|---|---|\n')
    texts = {}
    order = []
    missing = []
    for name, version, license_, repo, directory in linked:
        source = repo or f'https://crates.io/crates/{name}/{version}'
        parts.append(f'| {name} | {version} | {license_} | {source} |\n')
        files = license_files(directory)
        if not files:
            missing.append((name, version, license_, repo))
        for path in files:
            text = read(path)
            key = hashlib.sha256(text.encode()).hexdigest()
            if key not in texts:
                texts[key] = (text, [])
                order.append(key)
            texts[key][1].append(f'{name} {version}')
    parts.append('\n### License texts\n')
    for key in order:
        text, users = texts[key]
        parts.append('Used by ' + ', '.join(users) + ':\n')
        parts.append(fenced(text))
    if missing:
        # Their declared license, in its standard text: MIT naming the
        # project as holder; MPL-2.0 is reproduced above (cssparser)
        parts.append('### Crates without license files\n')
        parts.append('These crates ship no license file. Each is under the license its manifest declares, '
                     'in that license\'s standard text.\n')
        for name, version, license_, repo in missing:
            if license_ == 'MIT':
                holder = f'the {name} authors' + (f', {repo}' if repo else '')
                parts.append(f'{name} {version}:\n')
                parts.append(fenced(MIT_TEXT.format(holder=holder)))
            else:
                parts.append(f'{name} {version}: {license_}, whose full text is reproduced above.\n')
    return '\n'.join(parts)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--merman', required=True)
    parser.add_argument('--md4c', required=True)
    parser.add_argument('--out', required=True)
    parser.add_argument('--toolchain', default='1.95.0')
    parser.add_argument('--features', default='all-diagrams svg layout-cytoscape math png')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = build(args)
    if args.check:
        current = open(args.out, encoding='utf-8').read() if os.path.exists(args.out) else ''
        if current != text:
            print(f'{args.out} is stale: rerun packaging/notices/generate_notices.py', file=sys.stderr)
            return 1
        print('notices current')
        return 0
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'wrote {args.out}: {len(text)} bytes')
    return 0


if __name__ == '__main__':
    sys.exit(main())
